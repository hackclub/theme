import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync
} from 'fs'
import { dirname, join } from 'path'

rmSync('./dist', { recursive: true, force: true })

const run = (cmd: string[]) => {
  const result = Bun.spawnSync(cmd, { cwd: import.meta.dir })
  if (result.exitCode !== 0) {
    console.error(result.stdout.toString(), result.stderr.toString())
    process.exit(1)
  }
}

// 1. Pre-render the icon set (src/glyphs*.ts)
run(['bun', 'run', './scripts/gen-icons.tsx'])

// 2. Embed the prose stylesheet as a string (src/prose-css.ts)
const proseSource = join(
  dirname(Bun.resolveSync('@hackclub/css-base/package.json', import.meta.dir)),
  'src/prose.css'
)
writeFileSync(
  './src/prose-css.ts',
  `// Generated by build.ts from @hackclub/css-base — do not edit.\nexport const proseCSS = ${JSON.stringify(readFileSync(proseSource, 'utf8'))}\n`
)

// 3. Compile every file on its own. The output mirrors src/ one-to-one, so
// there is no bundling step (and no shared chunks) to go wrong; consumers'
// bundlers handle minification and tree-shaking.
const transpiler = new Bun.Transpiler({
  loader: 'ts',
  target: 'browser',
  tsconfig: { compilerOptions: { useDefineForClassFields: false } }
})

/** Node and browsers need explicit extensions on relative imports. */
const addExtensions = (code: string) =>
  code.replace(
    /((?:\bfrom|\bimport)\s*)(["'])(\.{1,2}\/[^"']+)\2/g,
    (_, keyword, quote, specifier) =>
      /\.[cm]?js$/.test(specifier)
        ? `${keyword}${quote}${specifier}${quote}`
        : `${keyword}${quote}${specifier}.js${quote}`
  )

const compile = (dir: string) => {
  for (const name of readdirSync(`./src/${dir}`)) {
    const rel = join(dir, name)
    if (statSync(`./src/${rel}`).isDirectory()) {
      compile(rel)
    } else if (name.endsWith('.ts') && !name.endsWith('.d.ts')) {
      const code = addExtensions(
        transpiler.transformSync(readFileSync(`./src/${rel}`, 'utf8'))
      )
      const out = `./dist/${rel.replace(/\.ts$/, '.js')}`
      if (!existsSync(dirname(out)))
        mkdirSync(dirname(out), { recursive: true })
      writeFileSync(out, code)
    }
  }
}
compile('')

// 4. Type declarations
run(['bunx', 'tsc', '-p', 'tsconfig.json'])
